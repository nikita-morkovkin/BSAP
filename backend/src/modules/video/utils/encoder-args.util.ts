import type { VideoStyleConfig } from '../types/video-style.type';

export const encoderArgs = (
  style: VideoStyleConfig,
  preview = false,
): string[] => [
  '-an',
  '-c:v',
  'libx264',
  '-preset',
  preview ? 'ultrafast' : 'veryfast',
  '-crf',
  '20',
  '-bf',
  '0',
  '-profile:v',
  'high',
  '-level:v',
  '5.2',
  '-pix_fmt',
  'yuv420p',
  '-r',
  String(style.fps),
  '-g',
  String(style.fps * 2),
  '-keyint_min',
  String(style.fps * 2),
  '-sc_threshold',
  '0',
  '-video_track_timescale',
  '90000',
  '-movflags',
  '+faststart',
  '-threads',
  '2',
];
